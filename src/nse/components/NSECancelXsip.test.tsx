import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import NSECancelXsip from './NSECancelXsip';
import * as service from '../services/nseXsipCancellationService';
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it('requires reason, review and explicit confirmation before sending once', async () => {
  const cancel = vi.spyOn(service, 'cancelNSEXsip').mockResolvedValue('Cancellation confirmed'); const done = vi.fn();
  render(<NSECancelXsip sipId="123" clientCode="TEST001" scheme="Test fund" investor="Test investor" onCancelled={done} />);
  fireEvent.click(screen.getByRole('button', { name: 'Cancel XSIP' }));
  fireEvent.change(screen.getByLabelText('Cancellation reason'), { target: { value: '07' } });
  fireEvent.click(screen.getByRole('button', { name: 'Review cancellation' }));
  expect(cancel).not.toHaveBeenCalled();
  expect(screen.getByRole('button', { name: 'Confirm XSIP cancellation' })).toBeDisabled();
  fireEvent.click(screen.getByRole('checkbox'));
  fireEvent.click(screen.getByRole('button', { name: 'Confirm XSIP cancellation' }));
  expect(await screen.findByText(/Cancellation confirmed/)).toBeInTheDocument();
  expect(cancel).toHaveBeenCalledExactlyOnceWith('TEST001', '123', '07', '');
  expect(done).toHaveBeenCalledOnce();
  expect(screen.queryByRole('button', { name: 'Confirm XSIP cancellation' })).not.toBeInTheDocument();
});
