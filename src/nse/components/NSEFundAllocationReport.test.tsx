import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import NSEFundAllocationReport from './NSEFundAllocationReport';
import { NSE_TOKEN_KEY } from '../services/nseApi';
afterEach(() => { cleanup(); vi.unstubAllGlobals(); sessionStorage.clear(); });
it('loads live report data through the wrapper and masks the remitter account', async () => {
  sessionStorage.setItem(NSE_TOKEN_KEY, 'test-token');
  const fetcher = vi.fn().mockResolvedValue({ ok: true, status: 200, text: async () => JSON.stringify({ response_status: 'S', report_data: [{ order_number: '123456789012', remitteraccountno: '000009876543', totalamount: '10000', totalallocatedamount: '0', allotment_flag: 'Y' }] }) });
  vi.stubGlobal('fetch', fetcher);
  render(<NSEFundAllocationReport />);
  fireEvent.click(screen.getByText('Fund allocation by order'));
  fireEvent.change(screen.getByLabelText('Payment provider'), { target: { value: '6' } });
  fireEvent.click(screen.getByRole('button', { name: 'Load fund allocation report' }));
  expect(await screen.findByText('Order 123456789012')).toBeInTheDocument();
  expect(screen.getByText('Account ending 6543')).toBeInTheDocument();
  expect(screen.queryByText('000009876543')).not.toBeInTheDocument();
  expect(screen.getByText('Order allocation')).toBeInTheDocument();
  expect(JSON.parse(fetcher.mock.calls[0][1].body).pg_agencyid).toBe('6');
});
