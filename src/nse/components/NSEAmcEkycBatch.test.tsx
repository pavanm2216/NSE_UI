import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import NSEAmcPause from './NSEAmcPause';
import NSEEkycRegistration from './NSEEkycRegistration';
import NSEAmcPauseReport from './NSEAmcPauseReport';
import { NSE_TOKEN_KEY } from '../services/nseApi';
afterEach(() => { cleanup(); vi.unstubAllGlobals(); sessionStorage.clear(); });
const mock = (body: unknown, status = 200) => { sessionStorage.setItem(NSE_TOKEN_KEY, 'test-token'); const fetcher = vi.fn().mockResolvedValue({ ok: status === 200, status, text: async () => JSON.stringify(body) }); vi.stubGlobal('fetch', fetcher); return fetcher; };
it('requires review and consent, then shows AMC service unavailability without retry', async () => {
  const fetcher = mock({ detail: JSON.stringify({ status: '404', message: 'Service unavailable.' }) }, 404);
  render(<NSEAmcPause id="123" client="TEST" />);
  fireEvent.click(screen.getByText('AMC pause / unpause'));
  fireEvent.change(screen.getByLabelText('Installment count'), { target: { value: '10' } });
  fireEvent.click(screen.getByRole('button', { name: 'Review AMC pause' }));
  expect(fetcher).not.toHaveBeenCalled();
  expect(screen.getByRole('button', { name: 'Confirm AMC pause request' })).toBeDisabled();
  fireEvent.click(screen.getByRole('checkbox'));
  fireEvent.click(screen.getByRole('button', { name: 'Confirm AMC pause request' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('unavailable');
  expect(fetcher).toHaveBeenCalledTimes(1);
});
it('provides an eKYC continuation link without claiming verified KYC', async () => {
  const fetcher = mock({ link: 'https://example.test/ekyc/123', message: 'Request received' });
  render(<NSEEkycRegistration onClose={vi.fn()} />);
  for (const [label, value] of [['RTA AMC code', 'TESTAMC'], ['Investor PAN', 'AAAAA1234A'], ['Investor mobile', '9000000000'], ['Investor email', 'investor@example.test']]) fireEvent.change(screen.getByLabelText(label), { target: { value } });
  fireEvent.click(screen.getByRole('button', { name: 'Review eKYC request' }));
  expect(fetcher).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('checkbox'));
  fireEvent.click(screen.getByRole('button', { name: 'Confirm eKYC request' }));
  expect(await screen.findByRole('link', { name: 'Continue investor eKYC' })).toHaveAttribute('href', 'https://example.test/ekyc/123');
  expect(fetcher).toHaveBeenCalledTimes(1);
  expect(fetcher).toHaveBeenCalledWith('/nse-api/ekyc/register', expect.objectContaining({ method: 'POST', body: JSON.stringify({ amcCode: 'TESTAMC', panNo: 'AAAAA1234A', mobileNo: '9000000000', invEmail: 'investor@example.test' }) }));
  expect(screen.queryByText(/service is pending/)).not.toBeInTheDocument();
  expect(screen.getByText(/Link creation does not confirm KYC/)).toBeInTheDocument();
});
it('fetches AMC pause history by request ID and shows activation separately', async () => {
  const fetcher = mock({ response_status: 'S', report_data: [{ sip_registration_no: '123', request_id: '567', date_of_activation: '16/01/2026', modified_instalments: '8' }] });
  render(<NSEAmcPauseReport />);
  fireEvent.click(screen.getByText('AMC pause history'));
  fireEvent.change(screen.getByLabelText('AMC pause request ID'), { target: { value: '567' } });
  fireEvent.click(screen.getByRole('button', { name: 'Load AMC pause history' }));
  expect(await screen.findByText('16/01/2026')).toBeInTheDocument();
  expect(JSON.parse(fetcher.mock.calls[0][1].body)).toEqual({ request_id: '567' });
});
