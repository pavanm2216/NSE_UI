import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import NSENftUpdates from './NSENftUpdates';
import { NSE_TOKEN_KEY } from '@/services/nseApi';
afterEach(() => { cleanup(); vi.unstubAllGlobals(); sessionStorage.clear(); });
const fill = (label: string, value: string) => fireEvent.change(screen.getByLabelText(label), { target: { value } });
it('reviews the primary bank separately and keeps 404 changes unconfirmed', async () => {
  sessionStorage.setItem(NSE_TOKEN_KEY, 'test-token');
  const fetcher = vi.fn().mockResolvedValue({ ok: false, status: 404, text: async () => JSON.stringify({ detail: '<html>404</html>' }) }); vi.stubGlobal('fetch', fetcher);
  render(<NSENftUpdates onClose={vi.fn()} />); fireEvent.click(screen.getByRole('button', { name: 'Primary bank' }));
  for (const [label, value] of [['AMC master code', 'TST'], ['Folio number', '123'], ['First holder PAN', 'AAAAA1234A'], ['Digital authorization channel', 'E'], ['First holder email', 'investor@example.test'], ['New primary bank account', '000123456789'], ['Primary account holder name', 'Test holder'], ['Primary bank IFSC', 'TEST0000123'], ['Primary account type master code', 'SB'], ['Primary bank name', 'Test bank'], ['Primary bank branch', 'Test branch']]) fill(label, value);
  fireEvent.click(screen.getByRole('button', { name: 'Review primary bank change' }));
  expect(fetcher).not.toHaveBeenCalled(); expect(screen.getByText('Ending 6789')).toBeInTheDocument();
  fireEvent.click(screen.getByRole('checkbox')); fireEvent.click(screen.getByRole('button', { name: 'Confirm primary bank change' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('unavailable');
});
it('checks document content before review and uploads only after consent', async () => {
  sessionStorage.setItem(NSE_TOKEN_KEY, 'test-token');
  const fetcher = vi.fn().mockResolvedValue({ ok: true, status: 200, text: async () => JSON.stringify({ img_name: 'test.tiff', status: 'SUCCESS', message: 'Uploaded successfully' }) }); vi.stubGlobal('fetch', fetcher);
  render(<NSENftUpdates onClose={vi.fn()} />); fireEvent.click(screen.getByRole('button', { name: 'Upload NFT document' }));
  fill('NFT image reference filename', 'test.tiff');
  fireEvent.change(screen.getByLabelText('NFT document'), { target: { files: [new File([new Uint8Array([73, 73, 42, 0, 8, 0, 0, 0])], 'test.tiff')] } });
  fireEvent.click(screen.getByRole('button', { name: 'Review NFT document' }));
  const confirm = await screen.findByRole('button', { name: 'Confirm NFT document upload' });
  expect(confirm).toBeDisabled(); expect(fetcher).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('checkbox')); fireEvent.click(confirm);
  expect(await screen.findByText(/Uploaded successfully/)).toBeInTheDocument();
  expect(fetcher).toHaveBeenCalledTimes(1); expect(JSON.parse(fetcher.mock.calls[0][1].body).img_name).toBe('test.tiff');
  expect(screen.queryByRole('button', { name: 'Confirm NFT document upload' })).not.toBeInTheDocument();
});
