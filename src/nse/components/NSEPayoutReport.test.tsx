import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import NSEPayoutReport from './NSEPayoutReport';
import { NSE_TOKEN_KEY } from '../services/nseApi';
afterEach(() => { cleanup(); vi.unstubAllGlobals(); sessionStorage.clear(); });
it('uses the non-demat endpoint and masks payee accounts while showing dispatch data', async () => {
  sessionStorage.setItem(NSE_TOKEN_KEY, 'test-token');
  const fetcher = vi.fn().mockResolvedValue({ ok: true, status: 200, text: async () => JSON.stringify({ response_status: 'S', report_data: [{ order_id: '123', scheme_name: 'Physical test fund', funds_payout_status: 'S,T,R', payout_desc: 'ELECTRONIC PAYMENT', instrm_bank: 'Test Bank', payee_acno: '000011112222', despatch_ref: 'TESTREF' }] }) });
  vi.stubGlobal('fetch', fetcher);
  render(<NSEPayoutReport nonDemat />);
  fireEvent.click(screen.getByRole('button', { name: 'Load payout details' }));
  expect(await screen.findByText('Physical test fund')).toBeInTheDocument();
  expect(fetcher).toHaveBeenCalledWith('/nse-api/reports/redemption-payout-non-demat', expect.any(Object));
  expect(screen.getByText('•••• 2222')).toBeInTheDocument();
  expect(screen.getByText('ELECTRONIC PAYMENT')).toBeInTheDocument();
  expect(screen.getByText('TESTREF')).toBeInTheDocument();
  expect(screen.getByText('S,T,R')).toBeInTheDocument();
  expect(screen.queryByText('000011112222')).not.toBeInTheDocument();
});
it('shows raw payout status, dates and masked accounts without asserting completion', async () => {
  sessionStorage.setItem(NSE_TOKEN_KEY, 'test-token');
  const fetcher = vi.fn().mockResolvedValue({ ok: true, status: 200, text: async () => JSON.stringify({ response_status: 'S', report_data: [{ order_id: '123', scheme_name: 'Test fund', allotted_amount: '50000', funds_payout_status: 'P', funds_payout_date: '09 APR 2024', account_no: '000011112222', first_applicant_pan: 'SECRET-PAN' }] }) });
  vi.stubGlobal('fetch', fetcher);
  render(<NSEPayoutReport />);
  expect(fetcher).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: 'Load payout details' }));
  expect(await screen.findByText('Test fund')).toBeInTheDocument();
  expect(screen.getByText('P', { selector: 'strong' })).toBeInTheDocument();
  expect(screen.getByText('•••• 2222')).toBeInTheDocument();
  expect(screen.queryByText('SECRET-PAN')).not.toBeInTheDocument();
  expect(screen.queryByText('Payout completed')).not.toBeInTheDocument();
});
