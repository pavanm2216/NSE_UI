import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import NSEEditStp from './NSEEditStp';
import * as service from '@/services/nseStpModificationService';
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it('reviews actual changes and requires confirmation before a single submission', async () => {
  const modify = vi.spyOn(service, 'modifyNSEStp').mockResolvedValue('Mutual funds confirmed the STP modification');
  render(<NSEEditStp id="123" client="TEST" scheme="Test fund" mode="PHYSICAL" current={{ amount: '1000' }} />);
  fireEvent.click(screen.getByRole('button', { name: 'Edit STP' }));
  fireEvent.change(screen.getByLabelText(/Installment amount/), { target: { value: '2000' } });
  fireEvent.click(screen.getByRole('button', { name: 'Review changes' }));
  expect(screen.getByText('1000 → 2000')).toBeInTheDocument();
  expect(modify).not.toHaveBeenCalled();
  expect(screen.getByRole('button', { name: 'Confirm STP changes' })).toBeDisabled();
  fireEvent.click(screen.getByRole('checkbox'));
  fireEvent.click(screen.getByRole('button', { name: 'Confirm STP changes' }));
  expect(await screen.findByText(/Mutual funds confirmed the STP modification/)).toBeInTheDocument();
  expect(modify).toHaveBeenCalledExactlyOnceWith('123', { amount: '2000' }, '', true, true, 'PHYSICAL');
});
