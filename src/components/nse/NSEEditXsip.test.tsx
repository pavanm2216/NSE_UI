import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import NSEEditXsip from './NSEEditXsip';
import * as service from '@/services/nseXsipModificationService';
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it('reviews actual changes and requires confirmation before a single submission', async () => {
  const modify = vi.spyOn(service, 'modifyNSEXsip').mockResolvedValue('Mutual funds confirmed the XSIP modification');
  render(<NSEEditXsip id="123" client="TEST" scheme="Test fund" current={{ amount: '1000' }} />);
  fireEvent.click(screen.getByRole('button', { name: 'Edit XSIP' }));
  fireEvent.change(screen.getByLabelText(/Installment amount/), { target: { value: '2000' } });
  fireEvent.click(screen.getByRole('button', { name: 'Review changes' }));
  expect(screen.getByText('1000 → 2000')).toBeInTheDocument();
  expect(modify).not.toHaveBeenCalled();
  expect(screen.getByRole('button', { name: 'Confirm XSIP changes' })).toBeDisabled();
  fireEvent.click(screen.getByRole('checkbox'));
  fireEvent.click(screen.getByRole('button', { name: 'Confirm XSIP changes' }));
  expect(await screen.findByText(/Mutual funds confirmed the XSIP modification/)).toBeInTheDocument();
  expect(modify).toHaveBeenCalledExactlyOnceWith('123', { amount: '2000' }, '', true, true);
});
