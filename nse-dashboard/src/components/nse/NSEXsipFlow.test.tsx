import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import NSEXsipFlow from './NSEXsipFlow';
import { nseApi } from '@/services/nseApi';
vi.mock('./NSEInvestorSelector', () => import('@/test/mockNSEInvestorSelector'));
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it('requires a real approved mandate and consent before registering an XSIP', async () => {
  vi.spyOn(nseApi, 'mandateStatus').mockResolvedValue({ response_status: 'S', report_data: [{ clientCode: 'TESTCL001', mandateId: '456', bankName: 'Test bank', status: 'APPROVED', amount: '10000' }] });
  const register = vi.spyOn(nseApi, 'registerXsip').mockResolvedValue({ reg_data: [{ client_code: 'TESTCL001', sch_code: 'TEST-GR', reg_status: 'REG_SUCCESS', reg_id: '12345' }] });
  const record = vi.fn();
  render(<NSEXsipFlow fund={{ name: 'Test fund', amc: 'Test AMC', amcCode: 'TEST_MF', plan: 'Direct', schemeCode: 'TEST-GR' }} onClose={vi.fn()} onRecord={record} onTrack={vi.fn()} />);
  fireEvent.change(screen.getByLabelText('Installment amount (₹)'), { target: { value: '3000' } });
  fireEvent.change(screen.getByLabelText('Start date'), { target: { value: '2099-10-15' } });
  fireEvent.click(screen.getByRole('button', { name: 'Continue to investor' }));
  await screen.findByRole('option', { name: /Test bank.*456/ });
  fireEvent.change(screen.getByLabelText('Approved XSIP mandate'), { target: { value: '456' } });
  fireEvent.change(screen.getByLabelText('EUIN declaration'), { target: { value: 'N' } });
  fireEvent.click(screen.getByRole('button', { name: 'Review XSIP' }));
  expect(register).not.toHaveBeenCalled();
  expect(screen.getByRole('button', { name: 'Register XSIP' })).toBeDisabled();
  fireEvent.click(screen.getByLabelText(/I confirm the schedule/));
  fireEvent.click(screen.getByRole('button', { name: 'Register XSIP' }));
  expect(await screen.findByText('XSIP registered')).toBeInTheDocument();
  expect(record).toHaveBeenCalledWith(expect.objectContaining({ live: true, registrationProduct: 'XSIP', sipRegistrationId: '12345', status: 'successful' }));
});
