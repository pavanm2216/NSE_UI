import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import NSESipReport from './NSESipReport';
import { nseApi } from '@/services/nseApi';
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it('shows separate management actions and mounts only the selected controls', async () => {
  vi.spyOn(nseApi, 'sipReport').mockResolvedValue({ response_status: 'S', report_data: [{ status: 'ACTIVE', sip_reg_number: '123', scheme_name: 'Test fund', installments_amount: '2000', frequency_type: 'MONTHLY', client_code: 'TEST' }] });
  render(<NSESipReport />);
  fireEvent.change(screen.getByLabelText('Client codes'), { target: { value: 'TEST' } });
  fireEvent.click(screen.getByRole('button', { name: "Load Mutual funds SIPs" }));
  await screen.findByText('Test fund');
  fireEvent.click(screen.getByText('Manage this plan'));
  expect(screen.queryByLabelText('AMC pause action')).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'AMC pause / unpause' }));
  expect(screen.getByLabelText('AMC pause action')).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Resend authorization', exact: true }));
  expect(screen.queryByLabelText('AMC pause action')).not.toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'Resend authorization email / SMS' })).toBeInTheDocument();
});
it('searches registrations by client and displays the matching scheme and schedule', async () => {
  const api = vi.spyOn(nseApi, 'sipReport').mockResolvedValue({ response_status: 'S', report_data: [{ status: 'ACTIVE', sip_reg_number: '123', scheme_name: 'Test fund', installments_amount: '2000', frequency_type: 'MONTHLY', client_code: 'TEST', start_date: '28 APR 2025', end_date: '27 APR 2026', no_of_installments: '12' }] });
  render(<NSESipReport />);
  expect(nseApi.sipReport).not.toHaveBeenCalled();
  fireEvent.change(screen.getByLabelText('Client codes'), { target: { value: 'TEST' } });
  fireEvent.click(screen.getByRole('button', { name: "Load Mutual funds SIPs" }));
  expect(await screen.findByText('Test fund')).toBeInTheDocument();
  expect(screen.getByText('ACTIVE')).toBeInTheDocument();
  expect(screen.getByText('28 APR 2025')).toBeInTheDocument();
  expect(api).toHaveBeenCalledWith({ client_code: 'TEST' });
});
it('clears stale management actions when the client changes', async () => {
  const api = vi.spyOn(nseApi, 'sipReport').mockResolvedValueOnce({ response_status: 'S', report_data: [{ scheme_name: 'Old fund', client_code: 'TEST' }] }).mockResolvedValueOnce({ response_status: 'S', report_data: [], error_remark: 'No record(s) found.' });
  render(<NSESipReport />);
  expect(nseApi.sipReport).not.toHaveBeenCalled();
  fireEvent.change(screen.getByLabelText('Client codes'), { target: { value: 'TEST' } });
  fireEvent.click(screen.getByRole('button', { name: "Load Mutual funds SIPs" }));
  await screen.findByText('Old fund');
  fireEvent.change(screen.getByLabelText('Client codes'), { target: { value: 'NEXT' } });
  expect(screen.queryByText('Old fund')).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: "Load Mutual funds SIPs" }));
  expect(await screen.findByText("Mutual funds returned no SIP registrations for these filters.")).toBeInTheDocument();
  expect(api).toHaveBeenLastCalledWith({ client_code: 'NEXT' });
});
it('shows backend failure instead of an empty report', async () => {
  vi.spyOn(nseApi, 'sipReport').mockResolvedValue({ response_status: 'F', report_data: [], error_remark: 'Invalid filter' });
  render(<NSESipReport />);
  expect(nseApi.sipReport).not.toHaveBeenCalled();
  fireEvent.change(screen.getByLabelText('Client codes'), { target: { value: 'TEST' } });
  fireEvent.click(screen.getByRole('button', { name: "Load Mutual funds SIPs" }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Invalid filter');
  expect(screen.queryByText("Mutual funds returned no SIP registrations for these filters.")).not.toBeInTheDocument();
});
